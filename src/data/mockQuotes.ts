export function getQuotesByProjectId(projectId: string): Quote[] {
  return mockQuotes
    .filter((quote) => quote.projectId === projectId)
    .sort((a, b) => b.version - a.version);
}

export function getQuoteById(id: string): Quote | undefined {
  return mockQuotes.find((quote) => quote.id === id);
}

export function getLatestQuote(projectId: string): Quote | undefined {
  return getQuotesByProjectId(projectId)[0];
}

export function getQuoteTimeline(projectId: string): QuoteTimelineStep[] {
  return mockQuoteTimelineByProject[projectId] ?? [];
}

export function calcItemAmount(quantity: number, unitPrice: number): number {
  return quantity * unitPrice;
}

export function calcQuoteTotals(input: {
  items: { amount: number }[];
  discount: number;
  shippingFee: number;
  extraFee: number;
  tax: number;
}) {
  const subtotal = input.items.reduce((sum, item) => sum + item.amount, 0);
  const total =
    subtotal - input.discount + input.shippingFee + input.extraFee + input.tax;
  return { subtotal, total: Math.max(0, total) };
}
