export function getCustomerOwnedItemById(
  id: string,
): CustomerOwnedItem | undefined {
  return mockCustomerOwnedItems.find((item) => item.id === id);
}

export function getOwnedItemStats(items: CustomerOwnedItem[] = mockCustomerOwnedItems) {
  return {
    awaitingInbound: items.filter(
      (item) =>
        item.lifecycleStatus === "WAITING_CUSTOMER_SHIPMENT" ||
        item.lifecycleStatus === "CUSTOMER_SHIPPED",
    ).length,
    needReceiveConfirm: items.filter(
      (item) => item.lifecycleStatus === "RECEIPT_CONFIRMATION_REQUIRED",
    ).length,
    anomaly: items.filter((item) => item.isAnomaly).length,
    awaitingLabel: items.filter(
      (item) => item.lifecycleStatus === "LABEL_PENDING",
    ).length,
    inProduction: items.filter(
      (item) => item.lifecycleStatus === "IN_PRODUCTION",
    ).length,
    awaitingReturn: items.filter(
      (item) =>
        item.lifecycleStatus === "RETURN_PENDING" ||
        item.lifecycleStatus === "PRODUCTION_COMPLETED",
    ).length,
  };
}

