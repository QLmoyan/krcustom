export function getOrderById(id: string): Order | undefined {
  return mockOrders.find((order) => order.id === id);
}

export function getOrderByProjectId(projectId: string): Order | undefined {
  return mockOrders.find((order) => order.projectId === projectId);
}

export function getOrdersByCustomer(): Order[] {
  return [...mockOrders].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
}

export function orderTypeLabel(type: OrderType): string {
  switch (type) {
    case "DIRECT_PURCHASE":
      return "바로 구매";
    case "QUOTE_BASED":
      return "견적 주문";
    case "CUSTOMER_OWNED_ITEM":
      return "고객 소지품";
    default:
      return type;
  }
}

export function getSellerOrderStats(orders: Order[] = mockOrders) {
  return {
    paymentPending: orders.filter(
      (o) =>
        o.status === OrderStatus.PAYMENT_PENDING ||
        o.status === OrderStatus.PAYMENT_PROCESSING,
    ).length,
    newPaid: orders.filter(
      (o) =>
        o.status === OrderStatus.PAID ||
        o.status === OrderStatus.ORDER_CONFIRMED,
    ).length,
    customerShipment: orders.filter(
      (o) => o.status === OrderStatus.CUSTOMER_SHIPMENT_PENDING,
    ).length,
    inProduction: orders.filter((o) => o.status === OrderStatus.IN_PRODUCTION)
      .length,
    shippingPending: orders.filter(
      (o) =>
        o.status === OrderStatus.SHIPPING_PENDING ||
        o.status === OrderStatus.PRODUCTION_COMPLETED,
    ).length,
    refund: orders.filter(
      (o) =>
        o.status === OrderStatus.REFUND_REQUESTED ||
        o.status === OrderStatus.REFUND_PROCESSING,
    ).length,
  };
}
